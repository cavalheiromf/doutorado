#!/usr/bin/env python3
"""Run HyPhy Contrast-FEL on the corrected OSCA3-only datasets.

The analysis reuses the validated four-sequence OSCA3 codon alignments and
labeled tree generated by 03_run_hyphy_osca3_only.py. OSCA4 is never included.
Two gap-filtering variants are analyzed, and all commands, checksums, logs,
raw JSON results, and site-level summaries are retained.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
import subprocess
from datetime import datetime, timezone
from pathlib import Path


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def run(command: list[str], stdout: Path, stderr: Path, threads: int) -> None:
    environment = os.environ.copy()
    environment["OMP_NUM_THREADS"] = str(threads)
    with stdout.open("w") as out_handle, stderr.open("w") as err_handle:
        subprocess.run(
            command,
            check=True,
            stdout=out_handle,
            stderr=err_handle,
            env=environment,
        )


def find_table(payload: dict) -> tuple[list[str], list[list[object]]]:
    """Return the Contrast-FEL MLE headers and rows from a HyPhy JSON file."""
    headers = payload.get("MLE", {}).get("headers")
    content = payload.get("MLE", {}).get("content")
    if not headers or not content:
        raise ValueError("HyPhy JSON lacks MLE headers/content")
    header_names = [item[0] if isinstance(item, list) else item for item in headers]
    if isinstance(content, dict):
        rows = next(iter(content.values()))
    else:
        rows = content
    return header_names, rows


def site_map(path: Path) -> dict[int, int]:
    with path.open() as handle:
        reader = csv.DictReader(handle, delimiter="\t")
        return {
            int(row["filtered_site"]): int(row["unfiltered_site"])
            for row in reader
        }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--project", type=Path, default=Path(__file__).resolve().parents[2]
    )
    parser.add_argument(
        "--hyphy",
        type=Path,
        default=Path("/home/mfcaval/.local/share/mamba/envs/jcviEnv/bin/hyphy"),
    )
    parser.add_argument("--threads", type=int, default=4)
    parser.add_argument("--p-value", type=float, default=0.05)
    parser.add_argument("--q-value", type=float, default=0.20)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()

    project = args.project.resolve()
    input_dir = project / "03_synteny/results/hyphy_osca3_only_20261026"
    output = (
        args.output
        or project / "03_synteny/results/contrast_fel_osca3_only_20261026"
    ).resolve()
    output.mkdir(parents=True, exist_ok=True)

    tree = input_dir / "osca3_labeled.treefile"
    datasets = {
        "gap20": (
            input_dir / "osca3_codon_gap20.fasta",
            input_dir / "osca3_gap20_site_map.tsv",
        ),
        "gap50": (
            input_dir / "osca3_codon_gap50.fasta",
            input_dir / "osca3_gap50_site_map.tsv",
        ),
    }
    for path in [args.hyphy, tree, *(p for pair in datasets.values() for p in pair)]:
        if not path.exists():
            raise FileNotFoundError(path)

    version = subprocess.run(
        [str(args.hyphy), "--version"], check=True, capture_output=True, text=True
    ).stdout.strip()
    (output / "hyphy_version.txt").write_text(version + "\n")

    commands: dict[str, list[str]] = {}
    summary_rows: list[dict[str, object]] = []
    site_rows: list[dict[str, object]] = []
    for label, (alignment, map_path) in datasets.items():
        result = output / f"contrast_fel_{label}.json"
        command = [
            str(args.hyphy),
            "contrast-fel",
            "--alignment",
            str(alignment),
            "--tree",
            str(tree),
            "--code",
            "Universal",
            "--branch-set",
            "Test",
            "--branch-set",
            "Reference",
            "--srv",
            "Yes",
            "--permutations",
            "Yes",
            "--p-value",
            str(args.p_value),
            "--q-value",
            str(args.q_value),
            "--limit-to-sites",
            "null",
            "--save-lf-for-sites",
            "null",
            "--intermediate-fits",
            "/dev/null",
            "--kill-zero-lengths",
            "Yes",
            "--output",
            str(result),
        ]
        commands[label] = command
        run(
            command,
            output / f"contrast_fel_{label}.stdout.log",
            output / f"contrast_fel_{label}.stderr.log",
            args.threads,
        )

        payload = json.loads(result.read_text())
        headers, rows = find_table(payload)
        mapping = site_map(map_path)
        lower_headers = {name.lower(): index for index, name in enumerate(headers)}
        p_columns = [
            (name, index)
            for index, name in enumerate(headers)
            if "p-value" in name.lower()
        ]
        q_columns = [
            (name, index)
            for index, name in enumerate(headers)
            if "q-value" in name.lower()
        ]
        if not p_columns:
            raise ValueError(f"No p-value column found for {label}: {headers}")

        nominal_count = 0
        fdr_count = 0
        for filtered_site, row in enumerate(rows, 1):
            p_values = [float(row[index]) for _, index in p_columns]
            q_values = [float(row[index]) for _, index in q_columns]
            min_p = min(p_values)
            min_q = min(q_values) if q_values else None
            nominal = min_p <= args.p_value
            fdr = min_q is not None and min_q <= args.q_value
            nominal_count += int(nominal)
            fdr_count += int(fdr)
            if nominal or fdr:
                site_rows.append(
                    {
                        "analysis": label,
                        "filtered_site": filtered_site,
                        "unfiltered_site": mapping[filtered_site],
                        "min_p_value": min_p,
                        "min_q_value": min_q if min_q is not None else "NA",
                        "nominal_p_le_0.05": nominal,
                        "fdr_q_le_0.20": fdr,
                    }
                )

        summary_rows.append(
            {
                "analysis": label,
                "codons": len(rows),
                "nominal_sites_p_le_0.05": nominal_count,
                "fdr_sites_q_le_0.20": fdr_count,
                "result": result.name,
            }
        )

    summary_fields = list(summary_rows[0])
    with (output / "contrast_fel_summary.tsv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=summary_fields, delimiter="\t")
        writer.writeheader()
        writer.writerows(summary_rows)

    site_fields = [
        "analysis",
        "filtered_site",
        "unfiltered_site",
        "min_p_value",
        "min_q_value",
        "nominal_p_le_0.05",
        "fdr_q_le_0.20",
    ]
    with (output / "contrast_fel_candidate_sites.tsv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=site_fields, delimiter="\t")
        writer.writeheader()
        writer.writerows(site_rows)

    inputs = [tree, *(p for pair in datasets.values() for p in pair)]
    provenance = {
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "biological_scope": "OSCA3 only; OSCA4 excluded",
        "software": {"hyphy": version},
        "parameters": {
            "branch_sets": ["Test", "Reference"],
            "srv": True,
            "permutations": True,
            "p_value": args.p_value,
            "q_value": args.q_value,
            "threads": args.threads,
        },
        "commands": commands,
        "sha256": {str(path): sha256(path) for path in inputs},
    }
    (output / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")
    print(json.dumps({"summary": summary_rows, "candidate_sites": site_rows}, indent=2))


if __name__ == "__main__":
    main()
